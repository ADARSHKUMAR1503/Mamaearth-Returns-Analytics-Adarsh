
import json
import os
import re
from pathlib import Path

from google import genai
from google.genai import types


# --------------------------------------------------
# 1. FILE PATHS AND CONFIGURATION
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent
FINDINGS_FILE = BASE_DIR / "findings.json"
OUTPUT_FILE = BASE_DIR / "sample_output.txt"

MODEL_NAME = "gemini-3.8-flash"

# Brief requires at least 10 seconds.
# Set timeout to 30 seconds to allow the API enough time.
REQUEST_TIMEOUT_MS = 30_000


# --------------------------------------------------
# 2. REQUIRED FIGURES FOR VALIDATION
# --------------------------------------------------

REQUIRED_FIGURES = {
    "cleaned revenue": ["97,358.30", "97358.30", "97358.3"],
    "COD return rate": ["44.4"],
    "highest-risk segment return rate": ["54.5"],
    "duplicate revenue difference": [
        "2,501.90",
        "2501.90",
        "2501.9",
    ],
    "March corrected revenue": [
        "20,318.90",
        "20318.90",
        "20318.9",
    ],
}


# --------------------------------------------------
# 3. LOAD FINDINGS
# --------------------------------------------------

def load_findings() -> dict:
    """Load the analysis results generated by clean_and_eda.py."""

    if not FINDINGS_FILE.exists():
        raise FileNotFoundError(
            f"Missing findings file: {FINDINGS_FILE}\n"
            "Run analysis/clean_and_eda.py first."
        )

    with FINDINGS_FILE.open("r", encoding="utf-8") as file:
        findings = json.load(file)

    return findings


# --------------------------------------------------
# 4. FORMAT NUMBERS FOR THE NARRATIVE
# --------------------------------------------------

def format_money(value) -> str:
    """Format a numeric value as a comma-separated amount."""
    return f"{float(value):,.2f}"


def validate_findings(findings: dict) -> None:
    """Check that required fields exist before generating a narrative."""

    required_keys = [
        "cleaned_total_revenue_inr",
        "raw_total_revenue_inr",
        "duplicate_reconciliation_delta_inr",
        "return_rate_by_payment",
        "highest_risk_segment",
        "true_peak_month",
        "outlier_inflated_month",
    ]

    missing = [key for key in required_keys if key not in findings]

    if missing:
        raise ValueError(
            f"findings.json is missing required keys: {missing}"
        )

    for key in [
        "cleaned_total_revenue_inr",
        "raw_total_revenue_inr",
        "duplicate_reconciliation_delta_inr",
    ]:
        if not isinstance(findings[key], (int, float)):
            raise ValueError(f"{key} must be numeric.")

    if "COD" not in findings["return_rate_by_payment"]:
        raise ValueError("COD return rate is missing.")

    if "return_rate_pct" not in findings["highest_risk_segment"]:
        raise ValueError("Highest-risk segment return rate is missing.")

    if "month" not in findings["true_peak_month"]:
        raise ValueError("True peak month is missing.")

    if "revenue_inr" not in findings["true_peak_month"]:
        raise ValueError("True peak month revenue is missing.")


# --------------------------------------------------
# 5. NUMERIC CONTENT VALIDATION
# --------------------------------------------------

def validate_narrative(narrative: str) -> list[str]:
    """
    Validate the narrative against the required sections and figures.
    Returns a list of validation errors.
    """

    errors = []

    if not narrative or not narrative.strip():
        return ["Narrative is empty."]

    # Require all three SCR sections.
    for heading in ["Situation", "Complication", "Resolution"]:
        if not re.search(
            rf"\b{heading}\b",
            narrative,
            flags=re.IGNORECASE,
        ):
            errors.append(f"Missing SCR section: {heading}")

    # Validate each required numerical figure.
    for label, accepted_values in REQUIRED_FIGURES.items():
        if not any(value in narrative for value in accepted_values):
            errors.append(
                f"Required figure missing or formatted unexpectedly: {label}"
            )

    # Check that March is explicitly mentioned.
    if not re.search(r"\bMarch\b|\b2026-03\b", narrative, re.IGNORECASE):
        errors.append("March peak month is not explicitly mentioned.")

    return errors


# --------------------------------------------------
# 6. OFFLINE NARRATIVE FALLBACK
# --------------------------------------------------

def generate_scr_narrative_offline(findings: dict) -> dict:
    """
    Generate a deterministic narrative without an API key or network.
    All numerical values come from findings.json.
    """

    validate_findings(findings)

    cleaned_revenue = format_money(
        findings["cleaned_total_revenue_inr"]
    )
    raw_revenue = format_money(
        findings["raw_total_revenue_inr"]
    )
    duplicate_delta = format_money(
        findings["duplicate_reconciliation_delta_inr"]
    )

    cod_rate = findings["return_rate_by_payment"]["COD"]

    risk_segment = findings["highest_risk_segment"]
    risk_payment = risk_segment["payment_method"]
    risk_tier = risk_segment["city_tier"]
    risk_rate = risk_segment["return_rate_pct"]

    peak = findings["true_peak_month"]
    peak_month = peak["month"]
    peak_revenue = format_money(peak["revenue_inr"])

    inflated = findings["outlier_inflated_month"]
    apparent_revenue = format_money(
        inflated["apparent_revenue_inr"]
    )
    corrected_revenue = format_money(
        inflated["corrected_revenue_inr"]
    )

    month_label = peak_month
    if peak_month == "2026-03":
        month_label = "March 2026"

    narrative = f"""Situation

The cleaned orders dataset records total revenue of INR {cleaned_revenue}. The raw dataset reported INR {raw_revenue}, so the duplicate reconciliation difference is INR {duplicate_delta}. COD orders have a return rate of {cod_rate}%.

Complication

The highest-risk segment is payment method {risk_payment} in city tier {risk_tier}, with a return rate of {risk_rate}%. The apparent January revenue of INR {apparent_revenue} was inflated by quantity outliers; the corrected January revenue is INR {corrected_revenue}.

Resolution

Use the cleaned revenue of INR {cleaned_revenue} for reporting and investigate COD returns in the highest-risk segment. After correcting for the quantity outliers, {month_label} is the true peak month, with revenue of INR {peak_revenue}. Keep the duplicate reconciliation difference of INR {duplicate_delta} visible in the audit trail.
"""

    errors = validate_narrative(narrative)

    if errors:
        return {
            "status": "error",
            "narrative": None,
            "message": "Offline narrative validation failed: "
            + "; ".join(errors),
        }

    return {
        "status": "success",
        "narrative": narrative,
        "tokens": 0,
    }


# --------------------------------------------------
# 7. GEMINI-POWERED NARRATIVE
# --------------------------------------------------

def generate_scr_narrative(findings: dict) -> dict:
    """
    Generate a Situation-Complication-Resolution narrative with Gemini.
    If the API key is missing or the request fails, use offline fallback.
    """

    try:
        validate_findings(findings)
    except Exception as exc:
        return {
            "status": "error",
            "narrative": None,
            "message": f"Invalid findings data: {exc}",
        }

    api_key = os.getenv("GEMINI_API_KEY")

    # No key? Use offline mode.
    if not api_key:
        print("GEMINI_API_KEY not found. Using offline narrative.")
        return generate_scr_narrative_offline(findings)

    try:
        client = genai.Client(
            api_key=api_key,
            http_options=types.HttpOptions(
                timeout=REQUEST_TIMEOUT_MS
            ),
        )

        system_instruction = """
You are a senior data analyst writing for Mamaearth's regional
operations and finance heads.

Write an executive-ready business narrative using the
Situation, Complication, Resolution (SCR) framework.

Strict requirements:
1. Use exactly these three section headings:
   Situation
   Complication
   Resolution
2. Use the supplied findings JSON as the only source of numerical facts.
3. Do not invent, estimate, or change any figures.
4. Preserve the supplied numerical values accurately.
5. Use INR for revenue figures.
6. Explain the duplicate revenue difference and the impact of
   quantity outliers on the apparent monthly revenue.
7. Mention the COD return rate and the highest-risk segment.
8. Identify the true peak month and its corrected revenue.
9. Keep the narrative concise, clear, and useful for business decisions.
10. Do not add unsupported claims or additional statistics.
"""

        prompt = f"""
Create the requested SCR narrative from these findings.

FINDINGS JSON:
{json.dumps(findings, indent=2, ensure_ascii=False)}

Important required figures to preserve:
- Cleaned revenue: {findings["cleaned_total_revenue_inr"]}
- COD return rate: {findings["return_rate_by_payment"]["COD"]}
- Highest-risk segment return rate:
  {findings["highest_risk_segment"]["return_rate_pct"]}
- Duplicate reconciliation difference:
  {findings["duplicate_reconciliation_delta_inr"]}
- True peak month: {findings["true_peak_month"]["month"]}
- True peak month revenue:
  {findings["true_peak_month"]["revenue_inr"]}
- Apparent January revenue:
  {findings["outlier_inflated_month"]["apparent_revenue_inr"]}
- Corrected January revenue:
  {findings["outlier_inflated_month"]["corrected_revenue_inr"]}

Return only the narrative, with the three required headings.
"""

        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.0,
                max_output_tokens=600,
            ),
        )

        narrative = (response.text or "").strip()

        # Validate generated content before accepting it.
        errors = validate_narrative(narrative)

        if errors:
            print("Gemini output did not pass validation:")
            for error in errors:
                print(f" - {error}")

            print("Using offline narrative instead.")
            return generate_scr_narrative_offline(findings)

        usage = getattr(response, "usage_metadata", None)
        total_tokens = (
            getattr(usage, "total_token_count", 0) or 0
        )

        return {
            "status": "success",
            "narrative": narrative,
            "tokens": total_tokens,
        }

    except Exception as exc:
        # Includes API errors, timeouts, model errors and connection issues.
        print(f"Gemini API call failed: {exc}")
        print("Switching to offline narrative.")

        return generate_scr_narrative_offline(findings)


# --------------------------------------------------
# 8. SAVE AND VERIFY THE NARRATIVE
# --------------------------------------------------

def main() -> None:
    findings = load_findings()

    result = generate_scr_narrative(findings)

    if result["status"] != "success":
        raise RuntimeError(
            result.get("message", "Narrative generation failed.")
        )

    narrative = result["narrative"]

    # Run validation again before saving.
    errors = validate_narrative(narrative)

    if errors:
        raise AssertionError(
            "Final narrative failed validation:\n"
            + "\n".join(errors)
        )

    OUTPUT_FILE.write_text(
        narrative + "\n",
        encoding="utf-8",
    )

    print("\nNarrative generation: PASS")
    print(f"Mode: {'Gemini API' if result.get('tokens', 0) else 'Offline fallback'}")
    print(f"Token count: {result.get('tokens', 0)}")
    print(f"Saved to: {OUTPUT_FILE}")

    print("\nRequired figure validation:")
    for label, accepted_values in REQUIRED_FIGURES.items():
        passed = any(value in narrative for value in accepted_values)
        print(f"{'PASS' if passed else 'FAIL'} - {label}")

    print("\nGenerated narrative:\n")
    print(narrative)


if __name__ == "__main__":
    main()
